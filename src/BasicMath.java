public class BasicMath {
    public static void main(String[] args){
        // basic math
        int x = 50;
        int y = 10;

        // addition
        int additionResult = x + y;

        // multiplication
        int multiplicationResult = x * y;

        // division
        int divisionResult = x / y;

        // subtraction
        int subtractionResult = x - y;

        // modulus
        int modulusResult = x % y;

        System.out.println(x + " + " + y + ": " + additionResult);
        System.out.println(x + " * " + y + ": " + multiplicationResult);
        System.out.println(x + " / " + y + ": " + divisionResult);
        System.out.println(x + " - " + y + ": " + subtractionResult);
        System.out.print(x + " % " + y + ": " + modulusResult);
    }
}
