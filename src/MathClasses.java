public class MathClasses {
    public static void main(String[] args){
        double result;
        result = Math.pow(2,7); // returns number raised to power of another
        result = Math.abs(-10); // returns absolute value
        result = Math.round(5.48); // round to whole number
        result = Math.ceil(5.48); // rounds number up
        result = Math.floor(5.48); // rounds number down - same as Math.round()
        result = Math.max(3,10); // get the highest of two numbers
        result = Math.min(20,15); // get the lowest of two numbers

        System.out.print(result);
    }
}
